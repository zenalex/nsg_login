/// Отказ во входе через соцсеть, который НЕ является багом приложения.
///
/// Появился, потому что штатный отказ и настоящий сбой выглядели одинаково и
/// оба улетали в трекер как `fatal`. Разбор задачи NSG-SOFT/futbolista-tasks#1594:
/// в 18 событиях подряд сервер отвечал 403 и объяснял, что вход этим способом
/// в этой стране недоступен, а в другом кластере соединение просто рвалось по
/// таймауту. Ни то, ни другое чинить в коде нечего — но каждое падало как
/// критическая ошибка и попадало в очередь на разбор.
///
/// Смысл типа — дать вызывающей стороне отличить «пользователю нужно показать
/// сообщение» от «это дефект, о нём нужно сообщить». Первое перехватывается и
/// гасится, второе летит дальше как раньше.
class NsgSocialLoginException implements Exception {
  NsgSocialLoginException({
    required this.message,
    required this.method,
    this.code = 0,
  });

  /// Что показать пользователю. Сообщение сервера, если он его прислал.
  final String message;

  /// Метод входа — `PhoneLoginRequestGoogle` и подобные. Нужен в тексте
  /// исключения: без него отказы разных провайдеров склеиваются в один кластер.
  final String method;

  /// Код ответа сервера. `0` означает «сервер не ответил» — сетевая ошибка,
  /// а не отказ. Не путать с 500: та значила бы, что сервер ответил сбоем.
  final int code;

  /// Ожидаемый отказ: сервер осознанно не пустил (403), либо связь оборвалась.
  ///
  /// Всё остальное — 500, 404, неожиданные коды — остаётся дефектом и должно
  /// доезжать до трекера.
  bool get isExpected => code == 403 || code == 0;

  @override
  String toString() {
    final where = method.isEmpty ? 'unknown method' : method;
    final what = message.isEmpty ? 'no message from server' : message;
    return 'Social login refused ($where, code $code): $what';
  }
}
